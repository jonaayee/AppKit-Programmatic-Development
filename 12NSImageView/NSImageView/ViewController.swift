import Cocoa

class ViewController: NSViewController {
    
    var image: NSImage = NSImage(systemSymbolName: "hand.wave.fill", accessibilityDescription: "A waving hand")! // A resource is a constant generated by Xcode, currently empty
    var imageView = NSImageView()

    override func viewDidLoad() {
        super.viewDidLoad()

        // Do any additional setup after loading the view.
        
        configureUI()
    }

    override var representedObject: Any? {
        didSet {
        // Update the view, if already loaded.
        }
    }


    private func configureUI() {
        configureImageView()
        addSubViews([imageView])
        configureConstraints()
    }
    
    private func configureImageView() {
        imageView.image = image
        imageView.imageScaling = .scaleAxesIndependently
        imageView.contentTintColor = .systemRed // Changes the color of the symbol
    }
    
    private func addSubViews(_ views: [NSView]) {
        for subview in views {
            view.addSubview(subview)
        }
    }
    
    private func configureConstraints() {
        
        imageView.translatesAutoresizingMaskIntoConstraints = false
        
        NSLayoutConstraint.activate([
            imageView.centerXAnchor.constraint(equalTo: view.centerXAnchor),
            imageView.centerYAnchor.constraint(equalTo: view.centerYAnchor),
            imageView.widthAnchor.constraint(equalToConstant: 400),
            imageView.heightAnchor.constraint(equalToConstant: 400)
        ])
    }
}

